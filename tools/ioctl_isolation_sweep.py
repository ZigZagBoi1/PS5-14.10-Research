#!/usr/bin/env python3
"""Sweep ioctl command numbers with one connection per command.

Why this exists
---------------
A probe that walks a command range inside one connection cannot name the
command that kills the console. The loader buffers its output, so the capture
ends in the middle of a line written several commands earlier: 477b's capture
ends at `[13] ret=-` and the fatal call was `0x80108017`, four iterations later.
Everything between the cut and the real cause is invisible, and so is the
conclusion drawn from it.

One connection per command fixes both problems: the capture is either the
command's own result, or the connection stops answering and that command is the
last thing the console ever ran.

Usage::

    python tools/ioctl_isolation_sweep.py --ip 192.168.1.121 \\
        --device /dev/dmem1 --base 0x80108000 --range 0-0xff
    python tools/ioctl_isolation_sweep.py --ip 192.168.1.121 \\
        --device /dev/dmem1 --commands 0x10,0x17 --dry-run

The command number in `--range`/`--commands` is added to `--base`, so the
sweep can address `_IOW` groups (`0x8xxxxxxx`), `_IOR` groups (`0x4xxxxxxx`)
or raw encodings by setting `--base 0`.

A connection that stops answering is retried nowhere: the sweep stops, prints
what it learned and needs the console relaunched. `--wait-for-loader` turns
that into a resume point for the rest of the range.

Offline test: `python -m unittest tools.test_ioctl_isolation_sweep`
"""

import argparse
import re
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from send_probe import STATUS_COMPLETE, loader_is_up, send_lua, wait_for_loader


PROBE_TEMPLATE = '''-- generated by tools/ioctl_isolation_sweep.py
-- Unbuffered stdout: a buffered probe that dies loses the lines that
-- would have named the command, which is how 477b misled 477c-478m.
io.stdout:setvbuf("no")
print("=== IOCTL SWEEP {tag} cmd=0x{cmd:08X} ===")

local function to_num(v)
    if type(v) == "table" and v.tonumber then return v:tonumber() end
    return tonumber(v) or 0
end
local function make_syscall(num)
    local t = {{}}
    for k, v in pairs(syscall.pipe) do t[k] = v end
    t.syscall_no = num
    setmetatable(t, getmetatable(syscall.pipe))
    return t
end
local function sgn(v)
    local h, l = 0, to_num(v)
    if type(v) == "table" and v.h then h, l = v.h, v.l end
    if h ~= 0 or l >= 0x80000000 then return -1 end
    return l
end
local function put_str(s)
    local buf = memory.alloc(#s + 1)
    for i = 1, #s do pcall(function() memory.write_byte(buf + i - 1, string.byte(s, i)) end) end
    pcall(function() memory.write_byte(buf + #s, 0) end)
    return buf
end
local function rd32(a)
    local ok, v = pcall(function() return memory.read_dword(a) end)
    if ok then return to_num(v) end
    return -1
end

local fd = sgn(make_syscall(5)(uint64(put_str("{device}")), uint64({flags}), uint64(0)))
print("[open] fd=" .. fd)
if fd >= 0 then
    local page = memory.alloc(0x{arg_size:X})
    for off = 0, 0x{arg_size:X} - 4, 4 do
        pcall(function() memory.write_dword(page + off, 0) end)
    end
    local ok, r = pcall(function()
        return make_syscall(54)(uint64(fd), uint64(0x{cmd:08X}), uint64(page))
    end)
    print(string.format("[cmd] ret=%d page=%08X %08X %08X %08X",
        ok and sgn(r) or -999, rd32(page), rd32(page + 4), rd32(page + 8), rd32(page + 12)))
    pcall(function() make_syscall(6)(uint64(fd)) end)
end
print("DONE")
'''

SURVIVED = "survived"
STOPPED = "stopped"


def _number(text):
    text = text.strip()
    if text.lower().startswith("0x"):
        return int(text, 16)
    return int(text, 10)


def parse_numbers(spec):
    """`0x10,0x17` or `0-0xff` or `0x00-0x17` into a list of ints."""
    numbers = []
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            lo, hi = (_number(x) for x in part.split("-", 1))
            if hi < lo:
                raise ValueError("descending range %r" % part)
            numbers.extend(range(lo, hi + 1))
        else:
            numbers.append(_number(part))
    return numbers


def build_probe(device, cmd, arg_size=0x100, flags=2):
    """Return the Lua source that issues exactly one ioctl."""
    return PROBE_TEMPLATE.format(
        tag=Path(device).name, cmd=cmd, device=device,
        arg_size=arg_size, flags=flags)


def classify(status, capture=b""):
    """Map a transport status and capture onto survived/stopped."""
    if status == STATUS_COMPLETE:
        return SURVIVED
    return STOPPED


def sweep(ip, port, device, commands, base, arg_size, flags, dry_run=False,
          stop_on_death=True, wait_seconds=0, log=print):
    results = []
    with tempfile.TemporaryDirectory(prefix="ioctl_sweep_") as tmp:
        for offset in commands:
            cmd = base + offset
            probe = build_probe(device, cmd, arg_size=arg_size, flags=flags)
            path = Path(tmp) / ("cmd_%08x.lua" % cmd)
            path.write_text(probe, encoding="utf-8")
            if dry_run:
                log("[dry] 0x%08X" % cmd)
                continue
            log("[*] 0x%08X" % cmd)
            status = send_lua(ip, port, str(path), save=False)
            verdict = classify(status)
            results.append((cmd, status, verdict))
            log("    0x%08X -> %s (%s)" % (cmd, verdict, status))
            if verdict == STOPPED:
                if stop_on_death:
                    log("[!] stopped at 0x%08X; relaunch the console to continue" % cmd)
                    if wait_seconds:
                        if wait_for_loader(ip, port, timeout=wait_seconds,
                                           log=log, answers=True):
                            continue
                    break
    return results


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--ip", default="10.0.0.96", help="PS5 address")
    parser.add_argument("--port", type=int, default=9026)
    parser.add_argument("--device", default="/dev/dmem1")
    parser.add_argument("--base", type=lambda s: int(s, 0), default=0x80108000)
    parser.add_argument("--range", dest="range_spec", default="0-0xff",
                        help="offsets added to --base, e.g. 0-0xff or 0x00-0x17")
    parser.add_argument("--commands", help="explicit offsets, e.g. 0x10,0x17")
    parser.add_argument("--arg-size", type=lambda s: int(s, 0), default=0x100)
    parser.add_argument("--flags", type=lambda s: int(s, 0), default=2,
                        help="open(2) flags (default O_RDWR)")
    parser.add_argument("--wait-for-loader", type=float, default=0.0,
                        help="seconds to wait for a relaunch after a stop")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    if not args.dry_run and not loader_is_up(args.ip, args.port):
        print("[!] loader is not accepting connections on %s:%d"
              % (args.ip, args.port))
        return 2

    commands = parse_numbers(args.commands or args.range_spec)
    results = sweep(args.ip, args.port, args.device, commands, args.base,
                    args.arg_size, args.flags, dry_run=args.dry_run,
                    wait_seconds=args.wait_for_loader)
    if results:
        survived = sum(1 for _c, _s, v in results if v == SURVIVED)
        print("[*] %d commands, %d survived, %d stopped the console"
              % (len(results), survived, len(results) - survived))
    return 0


if __name__ == "__main__":
    sys.exit(main())
